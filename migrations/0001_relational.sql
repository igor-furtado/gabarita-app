CREATE TABLE workspaces (
 id integer PRIMARY KEY, version integer NOT NULL DEFAULT 0,
 created_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT workspaces_version_check CHECK (version >= 0)
);
CREATE TABLE profiles (
 workspace_id integer PRIMARY KEY REFERENCES workspaces(id) ON DELETE CASCADE,
 name text NOT NULL DEFAULT ''
);
CREATE TABLE study_plans (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 workspace_id integer NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
 target text NOT NULL DEFAULT '', exam_date date, start_date date NOT NULL,
 weekly_hours double precision NOT NULL DEFAULT 14, configured boolean NOT NULL DEFAULT false,
 created_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT study_plans_hours_check CHECK (weekly_hours BETWEEN 1 AND 70),
 CONSTRAINT study_plans_target_check CHECK (NOT configured OR length(trim(target)) > 0)
);
CREATE UNIQUE INDEX study_plans_workspace_idx ON study_plans(workspace_id);
CREATE TABLE subjects (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), plan_id uuid NOT NULL REFERENCES study_plans(id) ON DELETE CASCADE,
 name text NOT NULL, weight double precision NOT NULL DEFAULT 1, material_url text,
 position integer GENERATED BY DEFAULT AS IDENTITY, created_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT subjects_name_check CHECK (length(trim(name)) > 0),
 CONSTRAINT subjects_weight_check CHECK (weight BETWEEN 1 AND 10),
 CONSTRAINT subjects_position_check CHECK (position >= 0)
);
CREATE INDEX subjects_plan_weight_idx ON subjects(plan_id, weight DESC, position);
CREATE TABLE topics (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), subject_id uuid NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
 name text NOT NULL, is_read boolean NOT NULL DEFAULT false, is_mastered boolean NOT NULL DEFAULT false,
 position integer GENERATED BY DEFAULT AS IDENTITY, created_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT topics_name_check CHECK (length(trim(name)) > 0),
 CONSTRAINT topics_position_check CHECK (position >= 0)
);
CREATE INDEX topics_subject_position_idx ON topics(subject_id,position);
CREATE TABLE study_sessions (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), topic_id uuid NOT NULL REFERENCES topics(id) ON DELETE CASCADE,
 studied_on date NOT NULL, minutes double precision NOT NULL, recall text NOT NULL DEFAULT '',
 questions integer NOT NULL DEFAULT 0, correct integer NOT NULL DEFAULT 0, kind text NOT NULL,
 position integer GENERATED BY DEFAULT AS IDENTITY, created_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT sessions_minutes_check CHECK (minutes BETWEEN 1 AND 600),
 CONSTRAINT sessions_questions_check CHECK (questions BETWEEN 0 AND 1000 AND correct BETWEEN 0 AND questions),
 CONSTRAINT sessions_kind_check CHECK (kind IN ('reading','active','mock')),
 CONSTRAINT sessions_position_check CHECK (position >= 0)
);
CREATE INDEX sessions_topic_date_idx ON study_sessions(topic_id,studied_on DESC);
CREATE INDEX sessions_date_idx ON study_sessions(studied_on DESC);
CREATE TABLE reviews (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), topic_id uuid NOT NULL REFERENCES topics(id) ON DELETE CASCADE,
 due_on date NOT NULL, interval_days integer NOT NULL, done boolean NOT NULL DEFAULT false,
 position integer GENERATED BY DEFAULT AS IDENTITY, created_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT reviews_interval_check CHECK (interval_days IN (1,7,30)),
 CONSTRAINT reviews_position_check CHECK (position >= 0)
);
CREATE INDEX reviews_topic_idx ON reviews(topic_id);
CREATE INDEX reviews_pending_due_idx ON reviews(due_on,topic_id) WHERE NOT done;
CREATE UNIQUE INDEX reviews_pending_topic_interval_idx ON reviews(topic_id,interval_days) WHERE NOT done;
CREATE TABLE error_reasons (
 id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY, label text NOT NULL,
 CONSTRAINT error_reasons_label_check CHECK (length(trim(label)) > 0)
);
CREATE UNIQUE INDEX error_reasons_label_idx ON error_reasons(label);
CREATE TABLE error_entries (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), subject_id uuid NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
 topic_label text NOT NULL DEFAULT '', reason_id integer NOT NULL REFERENCES error_reasons(id) ON DELETE RESTRICT,
 learned_rule text NOT NULL, source text NOT NULL DEFAULT '', resolved boolean NOT NULL DEFAULT false,
 recorded_on date NOT NULL, position integer GENERATED BY DEFAULT AS IDENTITY, created_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT errors_rule_check CHECK (length(trim(learned_rule)) > 0),
 CONSTRAINT errors_position_check CHECK (position >= 0)
);
CREATE INDEX errors_subject_date_idx ON error_entries(subject_id,recorded_on DESC);
CREATE INDEX errors_reason_idx ON error_entries(reason_id);
CREATE INDEX errors_unresolved_idx ON error_entries(subject_id,recorded_on) WHERE NOT resolved;
CREATE TABLE reminders (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), subject_id uuid NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
 content text NOT NULL, kind text NOT NULL, streak integer NOT NULL DEFAULT 0,
 position integer GENERATED BY DEFAULT AS IDENTITY, created_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT reminders_content_check CHECK (length(trim(content)) > 0),
 CONSTRAINT reminders_streak_check CHECK (streak >= 0),
 CONSTRAINT reminders_kind_check CHECK (kind IN ('memorize','attention','jurisprudence','observation')),
 CONSTRAINT reminders_position_check CHECK (position >= 0)
);
CREATE INDEX reminders_subject_idx ON reminders(subject_id);
CREATE INDEX reminders_priority_idx ON reminders(subject_id,position) WHERE streak < 3;
